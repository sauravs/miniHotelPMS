# -*- coding: utf-8 -*-
"""
THE GOLDEN PAYLOADS - the JSON contract a second client is built on, pinned.

Slice 15 adds a React UI that renders from `fixtures/api/` with no Python process and no socket.
That makes these files a contract in both directions, and this module holds both ends:

    layer 1   they are a faithful, current copy of the API. A rebuild is byte-identical, the
              matrix is complete, and every run a history row names resolves to a file. A
              `render.py` change that alters the payload fails HERE, as a stale rebuild, rather
              than as a broken UI three weeks later.
    layer 2   the shape every component depends on. Above all trap 1: a run that concluded
              nothing still carries `counts`, and `coverage.concluded` is the only honest gate
              for the tile row. That is pinned so nobody "tidies" the payload into a shape the
              UI then gets subtly wrong - in either direction.

Like `fixtures/demopms/`, these files are generated by a tool and never edited by hand.
"""
import json
import pathlib

import pytest

from hotelcontrols.kernel import Outcome
from hotelcontrols.providers.registry import names as provider_names
from hotelcontrols.spec import available, available_tenants
from hotelcontrols.web import App
from tools import dump_api_fixtures

GOLDEN = dump_api_fixtures.TARGET_DIR
OUTCOMES = {outcome.value for outcome in Outcome}


def golden(name: str):
    return json.loads((GOLDEN / name).read_text(encoding="utf-8"))


def matrix():
    app = App()
    for control_id in available():
        for tenant_id in available_tenants():
            for capture in app.captures_for(tenant_id):
                yield control_id, tenant_id, capture


RUNS = ["run/%s.%s.%s.json" % cell for cell in matrix()]


# ---------------------------------------------------------------------------------------
class TestLayer1TheGoldensAreTheApi:

    def test_a_rebuild_is_byte_identical(self):
        """Generated, never edited - the fixtures/demopms rule applied to the API's output.
        If this fails after a deliberate payload change: `python3 -m tools.dump_api_fixtures`,
        then read the diff, because the diff IS the contract change."""
        built = dump_api_fixtures.build()
        on_disk = {p.relative_to(GOLDEN).as_posix(): p.read_text(encoding="utf-8")
                   for p in GOLDEN.rglob("*.json")}
        assert sorted(on_disk) == sorted(built), "files added or missing - rebuild"
        stale = [name for name in built if built[name] != on_disk[name]]
        assert not stale, "stale golden payloads: %s" % ", ".join(stale[:10])

    def test_the_check_command_agrees(self):
        assert dump_api_fixtures.main(["--check"]) == 0

    def test_the_full_matrix_is_present(self):
        """Every control x every property x every capture. A UI tested on three hand-picked
        runs is a UI tested on three runs; the states that break a page are the rare ones."""
        assert len(RUNS) == len(available()) * sum(
            len(App().captures_for(t)) for t in available_tenants())
        for name in RUNS:
            assert (GOLDEN / name).is_file(), name

    def test_every_run_a_history_names_resolves_to_a_stored_payload(self):
        """R1's promise, kept by the fixtures too: a past run is re-read, never re-run."""
        for control_id in available():
            for row in golden("history/%s.json" % control_id)["runs"]:
                assert (GOLDEN / "runs" / ("%s.json" % row["run_id"])).is_file(), row

    def test_a_stored_run_says_what_the_live_run_said(self):
        """`/api/runs/<id>` is what the React history page links to. It must carry the same
        verdicts and evidence as the run it stores - only the spec-derived extras (readiness,
        execution plan) are not re-derived for a past run."""
        for name in RUNS:
            live = golden(name)
            stored = golden("runs/%s.json" % live["run_id"])
            for key in ("control_id", "tenant_id", "provider", "evidence", "as_of", "blocked",
                        "coverage", "verdicts"):
                assert stored[key] == live[key], (name, key)
            assert stored.get("counts") == live.get("counts"), name


